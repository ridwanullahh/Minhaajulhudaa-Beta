// Bundle all JSON data into a single TS file for Cloudflare compatibility
import fs from 'node:fs';
import path from 'node:path';

const dataDir = path.join(process.cwd(), 'data');
const outputPath = path.join(process.cwd(), 'src/lib/seed-data.ts');

const files = fs.readdirSync(dataDir).filter(f => f.endsWith('.json'));
const lines = ['// Auto-generated bundled seed data for Cloudflare edge compatibility', '// This file is generated by scripts/bundle-data.mjs - do not edit manually', '', 'export const seedData: Record<string, any[]> = {'];

for (const file of files) {
  const name = file.replace('.json', '');
  const content = fs.readFileSync(path.join(dataDir, file), 'utf8');
  lines.push(`  ${JSON.stringify(name)}: ${content},`);
}

lines.push('};');
lines.push('');
lines.push('export default seedData;');

fs.writeFileSync(outputPath, lines.join('\n'), 'utf8');
console.log(`Bundled ${files.length} collections -> ${outputPath}`);
console.log(`File size: ${fs.statSync(outputPath).size} bytes`);
